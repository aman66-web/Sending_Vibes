// A screen dressed in its design's own look, and its own words for the bits built into
// it (the envelope's "You've got mail", the runaway No's excuses) where those suit the
// design better than the usual ones.
function dress(screen: Screen, style: ScreenStyle, labels?: Labels): Screen {
  return labels ? { ...screen, style, labels } : { ...screen, style };
}

// Stickers sit near the edges and corners, clear of the words and of the sound button
// in the top right.
const sticker = (emoji: string, x: number, y: number, size: number, rotate = 0, motion?: Motion): Sticker => ({
  emoji,
  x,
  y,
  size,
  ...(rotate ? { rotate } : {}),
  ...(motion ? { motion } : {}),
});

